"""companion/layout.py: the public facade for the companion service's page
shell and component library.

Every responsibility lives in a sibling `companion/ui_*.py` module now:
`ui_base` for constants/routes/icons, `ui_time` for timestamp formatting,
`ui_nav` for the sidebar/tab-bar/preferences renderers, `ui_components`
for the escaped component library, `ui_shell` for the two full-document
builders (`login_shell`, `page_shell`) and the script-ordering constants
they share. Every name any caller has ever reached through `layout.X` is
re-exported here via an explicit import list — never a star import — so
existing call sites across `companion/pages/*.py` and the test suite keep
resolving unchanged.

stdlib-free itself: `html`/`datetime`/`zoneinfo` live in `ui_base`/
`ui_time`. No import from server/, and nothing from companion.auth beyond
the UI-theme cookie name, re-exported here for the same reason.
"""

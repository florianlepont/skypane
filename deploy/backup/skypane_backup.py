#!/usr/bin/env python3
"""SkyPane nightly off-box-ready state snapshot.

Runs on the VPS as user `skypane` from `skypane-backup.service`, writing
one dated, checksummed `tar.gz` archive of `/opt/skypane/state` into a
local archive directory per run. This job never leaves the VPS: the
off-box copy is a separate pull, over SSH, driven by the developer's Mac
through the forced-command gate in `deploy/backup/backup_gate.py`.

INCLUDE_FILES/INCLUDE_DIRS are an ALLOW-list, not a deny-list: a
`state/` entry added later but never added here is meant to be
*noticed* (a drift line to stdout, captured by journald), not silently
carried into or left out of the archive. `history.db` and `fleet.db`
are handled outside both lists: they are live WAL databases, never
copied byte-for-byte (see `snapshot_db()` below).
"""
import argparse
import fnmatch
import hashlib
import os
import re
import sqlite3
import sys
import tarfile
import tempfile
from datetime import datetime, timezone

DEFAULT_STATE_DIR = "/opt/skypane/state"
DEFAULT_ARCHIVE_DIR = "/var/lib/skypane-backup/archives"
DEFAULT_KEEP = 14

# Allow-list. devices.json is the per-device enrolment registry --
# included when present; losing it would make byos refuse every
# re-enrolment.
INCLUDE_FILES = (
    "byos_state.json",
    "devices.json",
    "device_config.json",
    "calendar_rules.json",
    "calendar_url.secret",
    "colour_rules.json",
    "manual_resolutions.json",
    "poll_state.json",
    "battery_state.json",
)
INCLUDE_DIRS = (
    "illustration_overrides",
    "gallery",
    "firmware",
)

# Live WAL databases archived through snapshot_db().
SNAPSHOT_DBS = ("history.db", "fleet.db")

# Known-regenerable/transient entries this job deliberately never
# archives and never reports as drift. Matched with fnmatch against
# each top-level state/ entry name.
KNOWN_EXCLUDED = (
    "panel.bin",
    "theme_previews",
    "caddy-access.log*",
    # Caddy names rotated logs caddy-access-<timestamp>.log[.gz].
    "caddy-access-*.log*",
    "history.db",
    "history.db-wal",
    "history.db-shm",
    "fleet.db",
    "fleet.db-wal",
    "fleet.db-shm",
    # Derived health signal regenerated by byos.
    "fleet_status.json",
    "*.lock",
    "*.tmp",
    "img",
)

# Per-device directories under <state>/devices/. This script is deliberately
# standalone (it runs without the server package), so the device id shape is
# duplicated here and mirrors server/device_dirs: "d_" plus 8 lowercase hex.
DEVICES_DIRNAME = "devices"
DEVICE_ID_RE = re.compile(r"\Ad_[0-9a-f]{8}\Z")
DEVICE_INCLUDE_FILES = (
    "device_config.json",
    "poll_state.json",
    "battery_state.json",
    "calendar_rules.json",
    "calendar_url.secret",
    "colour_rules.json",
    "manual_resolutions.json",
)
DEVICE_INCLUDE_DIRS = (
    "illustration_overrides",
    "gallery",
)
DEVICE_SNAPSHOT_DBS = ("history.db",)

ARCHIVE_RE = re.compile(r"^skypane-state-(\d{8}T\d{6}Z)\.tar\.gz$")


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--state-dir",
        default=DEFAULT_STATE_DIR,
        help="Directory to snapshot (default: %s)." % DEFAULT_STATE_DIR,
    )
    parser.add_argument(
        "--archive-dir",
        default=DEFAULT_ARCHIVE_DIR,
        help="Directory to write dated archives into (default: %s)." % DEFAULT_ARCHIVE_DIR,
    )
    parser.add_argument(
        "--keep",
        type=int,
        default=DEFAULT_KEEP,
        help="Number of newest archives to retain locally (default: %d)." % DEFAULT_KEEP,
    )
    return parser


def _is_known_excluded(name):
    return any(fnmatch.fnmatch(name, pattern) for pattern in KNOWN_EXCLUDED)


def _no_symlinks(tarinfo):
    # A symlink could point anywhere, including outside state/ entirely -
    # a restore (`tar -xzf ... -C state`) must only ever recreate regular
    # files/directories under the target directory, never follow a link
    # captured from the source host.
    if tarinfo.issym() or tarinfo.islnk():
        return None
    return tarinfo


def _no_symlinks_or_known_excluded(tarinfo):
    # Same symlink guard as _no_symlinks, plus KNOWN_EXCLUDED applied to
    # every entry's own basename -- an INCLUDE_DIRS directory is added
    # recursively (tarfile.add() walks it), so without this a
    # regenerable or transient file nested inside one (for example
    # firmware/registry.lock) would be archived just because its parent
    # directory is on the allow-list.
    if tarinfo.issym() or tarinfo.islnk():
        return None
    if _is_known_excluded(os.path.basename(tarinfo.name)):
        return None
    return tarinfo


def snapshot_db(src_path, dst_path):
    """Copy a SQLite database consistently while a writer may hold it open
    under WAL: sqlite3's own backup API copies pages under a shared lock
    rather than a byte-for-byte file copy, so a concurrent writer never
    produces a torn snapshot. `PRAGMA integrity_check` runs on the copy,
    never the live database, as the only proof the snapshot is sound.
    """
    label = os.path.basename(src_path)
    src = sqlite3.connect(src_path, timeout=30)
    dst = sqlite3.connect(dst_path)
    try:
        try:
            src.backup(dst)
        except sqlite3.DatabaseError as exc:
            raise RuntimeError("%s backup failed: %s" % (label, exc)) from exc
        row = dst.execute("PRAGMA integrity_check").fetchone()
        if row is None or row[0] != "ok":
            raise RuntimeError("%s backup failed integrity_check" % label)
    finally:
        dst.close()
        src.close()


def _device_ids(state_dir):
    """Sorted ids of real (non-symlink) device directories with a valid name."""
    devices_dir = os.path.join(state_dir, DEVICES_DIRNAME)
    if not os.path.isdir(devices_dir) or os.path.islink(devices_dir):
        return []
    ids = []
    for entry in sorted(os.listdir(devices_dir)):
        path = os.path.join(devices_dir, entry)
        if DEVICE_ID_RE.match(entry) and os.path.isdir(path) and not os.path.islink(path):
            ids.append(entry)
    return ids


def _add_device_dirs(tar, state_dir, tmp_dir):
    """Archive each device directory as devices/<id>/... : allow-listed
    files and directories plus a WAL-safe snapshot of its history.db.
    Snapshot temp files get a per-device name so devices never collide.
    """
    for dev_id in _device_ids(state_dir):
        src_dir = os.path.join(state_dir, DEVICES_DIRNAME, dev_id)
        arc_dir = "%s/%s" % (DEVICES_DIRNAME, dev_id)
        for db_name in DEVICE_SNAPSHOT_DBS:
            db_src = os.path.join(src_dir, db_name)
            if os.path.isfile(db_src) and not os.path.islink(db_src):
                snap_path = os.path.join(tmp_dir, "%s-%s" % (dev_id, db_name))
                snapshot_db(db_src, snap_path)
                tar.add(snap_path, arcname="%s/%s" % (arc_dir, db_name), filter=_no_symlinks)
        for filename in DEVICE_INCLUDE_FILES:
            path = os.path.join(src_dir, filename)
            if os.path.exists(path):
                tar.add(path, arcname="%s/%s" % (arc_dir, filename), filter=_no_symlinks)
        for dirname in DEVICE_INCLUDE_DIRS:
            path = os.path.join(src_dir, dirname)
            if os.path.isdir(path):
                tar.add(path, arcname="%s/%s" % (arc_dir, dirname), filter=_no_symlinks_or_known_excluded)


def _report_device_drift(state_dir):
    """Print a drift line for device directory names that are not valid ids
    and for unexpected entries inside valid device directories.
    """
    devices_dir = os.path.join(state_dir, DEVICES_DIRNAME)
    if not os.path.isdir(devices_dir):
        return
    valid = set(_device_ids(state_dir))
    known = set(DEVICE_INCLUDE_FILES) | set(DEVICE_INCLUDE_DIRS) | set(DEVICE_SNAPSHOT_DBS)
    for entry in sorted(os.listdir(devices_dir)):
        if entry not in valid:
            print("skypane_backup: not in include list: %s/%s" % (DEVICES_DIRNAME, entry))
            continue
        for inner in sorted(os.listdir(os.path.join(devices_dir, entry))):
            if inner in known or _is_known_excluded(inner):
                continue
            print("skypane_backup: not in include list: %s/%s/%s" % (DEVICES_DIRNAME, entry, inner))


def _write_checksum(archive_path):
    digest = hashlib.sha256()
    with open(archive_path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    name = os.path.basename(archive_path)
    sha_path = archive_path + ".sha256"
    partial = os.path.join(os.path.dirname(archive_path), ".partial-" + name + ".sha256")
    with open(partial, "w") as fh:
        fh.write("%s  %s\n" % (digest.hexdigest(), name))
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(partial, sha_path)


def _prune(archive_dir, keep):
    names = sorted(entry for entry in os.listdir(archive_dir) if ARCHIVE_RE.match(entry))
    stale = names[:-keep] if len(names) > keep else []
    for name in stale:
        for path in (os.path.join(archive_dir, name), os.path.join(archive_dir, name + ".sha256")):
            try:
                os.remove(path)
            except OSError:
                pass
    kept = set(names) - set(stale)
    # Second, independent pass: any .sha256 whose archive is gone (pruned
    # just above, or already missing before this run started) and any
    # leftover .partial-* from a previous, interrupted run.
    for entry in list(os.listdir(archive_dir)):
        if entry.endswith(".sha256"):
            base = entry[: -len(".sha256")]
            if ARCHIVE_RE.match(base) and base not in kept:
                try:
                    os.remove(os.path.join(archive_dir, entry))
                except OSError:
                    pass
        elif entry.startswith(".partial-"):
            try:
                os.remove(os.path.join(archive_dir, entry))
            except OSError:
                pass


def backup(state_dir, archive_dir, keep):
    """Build one dated, checksummed archive of `state_dir` into
    `archive_dir`, then prune to the newest `keep`. Returns 0/1, never
    raises: a missing state directory or a database that fails
    `integrity_check` is reported as one line and a non-zero return, not
    a traceback, since the systemd timer's journal is the only audience.
    """
    if not os.path.isdir(state_dir):
        print("skypane_backup: state directory not found: %s" % state_dir)
        return 1
    os.makedirs(archive_dir, exist_ok=True)

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    name = "skypane-state-%s.tar.gz" % timestamp
    final_path = os.path.join(archive_dir, name)
    partial_path = os.path.join(archive_dir, ".partial-" + name)

    with tempfile.TemporaryDirectory(dir=archive_dir, prefix=".tmp-") as tmp_dir:
        try:
            with tarfile.open(partial_path, "w:gz") as tar:
                for db_name in SNAPSHOT_DBS:
                    db_src = os.path.join(state_dir, db_name)
                    if os.path.exists(db_src):
                        snap_path = os.path.join(tmp_dir, db_name)
                        snapshot_db(db_src, snap_path)
                        tar.add(snap_path, arcname=db_name, filter=_no_symlinks)

                for filename in INCLUDE_FILES:
                    path = os.path.join(state_dir, filename)
                    if os.path.exists(path):
                        tar.add(path, arcname=filename, filter=_no_symlinks)
                for dirname in INCLUDE_DIRS:
                    path = os.path.join(state_dir, dirname)
                    if os.path.isdir(path):
                        tar.add(path, arcname=dirname, filter=_no_symlinks_or_known_excluded)
                _add_device_dirs(tar, state_dir, tmp_dir)
        except Exception as exc:
            try:
                os.remove(partial_path)
            except OSError:
                pass
            print("skypane_backup: snapshot failed: %s: %s" % (type(exc).__name__, exc))
            return 1

        # Drift: a top-level state/ entry that is neither included nor a
        # known-regenerable file is worth a line in the journal, even
        # though this run silently leaves it out either way.
        known = set(INCLUDE_FILES) | set(INCLUDE_DIRS) | set(SNAPSHOT_DBS) | {DEVICES_DIRNAME}
        for entry in sorted(os.listdir(state_dir)):
            if entry in known or _is_known_excluded(entry):
                continue
            print("skypane_backup: not in include list: %s" % entry)
        _report_device_drift(state_dir)

    with open(partial_path, "rb") as fh:
        os.fsync(fh.fileno())
    os.replace(partial_path, final_path)
    _write_checksum(final_path)
    _prune(archive_dir, keep)
    return 0


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        return backup(args.state_dir, args.archive_dir, args.keep)
    except Exception as exc:
        print("skypane_backup: %s: %s" % (type(exc).__name__, exc))
        return 1


if __name__ == "__main__":
    sys.exit(main())

"""Where private photo files live: `<state>/photos/<device_id>/<photo_id>.jpg`.

Leaf module: stdlib plus `server.device_dirs` for the device id shape.

Security invariant: the device id comes from a fleet.db row and the photo id
is generated by `new_photo_id` or read from a fleet.db row; neither is ever
taken from request text without a shape check. Both shapes are checked
before any string is joined onto a path, and a symlinked `photos` directory,
device directory or file is refused (a symlink is never legitimate here).
Directories are created 0700 whatever the process umask.
"""
from __future__ import annotations

import os
import re
import secrets
import sys

# Same repo-root sys.path bootstrap as server/device_dirs.py.
_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from server import device_dirs  # noqa: E402

PHOTOS_DIRNAME = "photos"
PHOTO_SUFFIX = ".jpg"
TEMP_PREFIX = ".up-"
DIR_MODE = 0o700
FILE_MODE = 0o600
# `\Z` (not `$`) so a trailing newline cannot slip through.
PHOTO_ID_RE = re.compile(r"\Aph_[0-9a-f]{16}\Z")


def new_photo_id() -> str:
    return "ph_" + secrets.token_hex(8)


def is_valid_photo_id(value: object) -> bool:
    return isinstance(value, str) and PHOTO_ID_RE.match(value) is not None


def _refuse_link(path: str) -> None:
    if os.path.islink(path):
        raise ValueError("photo path is a symbolic link")


def photo_dir(root: str, device_id: str) -> str:
    """The device's photo directory path; raises ValueError for a bad id or
    a symlinked `photos` or device directory. Touches nothing on disk."""
    if not isinstance(device_id, str) or not device_dirs.is_valid_device_id(device_id):
        raise ValueError("invalid device id")
    top = os.path.join(root, PHOTOS_DIRNAME)
    directory = os.path.join(top, device_id)
    _refuse_link(top)
    _refuse_link(directory)
    return directory


def photo_file(root: str, device_id: str, photo_id: str) -> str:
    """The final path of one photo; raises ValueError for a bad id or a
    symlinked component."""
    directory = photo_dir(root, device_id)
    if not is_valid_photo_id(photo_id):
        raise ValueError("invalid photo id")
    path = os.path.join(directory, photo_id + PHOTO_SUFFIX)
    _refuse_link(path)
    return path


def _make_private_dir(path: str) -> None:
    try:
        os.mkdir(path, DIR_MODE)
    except FileExistsError:
        pass
    # mkdir's mode is masked by the umask and an older directory may be
    # looser; the mode is set explicitly on the verified real directory.
    _refuse_link(path)
    os.chmod(path, DIR_MODE)


def ensure_photo_dir(root: str, device_id: str) -> str:
    """Create `photos/` and `photos/<device_id>/` (0700) and return the latter."""
    directory = photo_dir(root, device_id)
    _make_private_dir(os.path.join(root, PHOTOS_DIRNAME))
    _make_private_dir(directory)
    return directory

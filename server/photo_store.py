"""Private photo storage for a frame, reachable only through a capability.

Every user-facing function takes a `FrameManager` as its first argument.
The only way to get one is `authorize_manager`, which grants it to the
owner and the co-managers of a frame and to nobody else: the admin role is
never consulted, and a disabled user, a former co-manager, an unknown or
malformed device id and a missing user all get the same `PhotoAccessDenied`.
No function here accepts a role, an admin flag or a path. Callers must not
build a `FrameManager` themselves; one built without `authorize_manager`
carries no grant and every function refuses it. Authorise once per request:
the capability is a snapshot and is not re-checked against fleet.db.

Files live at `<state>/photos/<device_id>/<photo_id>.jpg` (see
`server.photo_paths`). Names are generated by the server; `add` takes bytes
only, so no uploaded name reaches the disk, the database or a log. Errors
carry fixed codes and never a path, a name or file content.

Quotas are checked inside the same write transaction that inserts the row,
so concurrent uploads cannot overshoot a limit.
"""
from __future__ import annotations

import contextlib
import dataclasses
import errno
import os
import sqlite3
import stat
import sys
import tempfile
import threading

# Same repo-root sys.path bootstrap as server/device_dirs.py.
_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from server import device_dirs, fleet_db, photo_paths, photo_quota  # noqa: E402
from server.photo import normalize  # noqa: E402

# Normalisation decodes untrusted images, which is memory heavy; at most two
# run at once in this process.
_NORMALIZE_SLOTS = threading.BoundedSemaphore(2)

# Module-private proof that a FrameManager came from authorize_manager.
_GRANT = object()


class PhotoAccessDenied(Exception):
    """The user may not manage this frame's photos. One message for every
    reason, so a refusal reveals nothing about the frame."""

    def __init__(self) -> None:
        super().__init__("photo_access_denied")


class PhotoNotFound(Exception):
    """No such photo on this frame (unknown, malformed or another frame's id)."""

    def __init__(self) -> None:
        super().__init__("photo_not_found")


@dataclasses.dataclass(frozen=True)
class FrameManager:
    """Capability to manage one frame's photos; see `authorize_manager`."""

    device_id: str
    user_id: int
    _grant: object = dataclasses.field(default=None, repr=False, compare=False)


@dataclasses.dataclass(frozen=True)
class PhotoMeta:
    """Metadata of one stored photo; never a path or a file name."""

    id: str
    width: int
    height: int
    size_bytes: int
    created_at: int
    seq: int


def authorize_manager(
    conn: sqlite3.Connection, device_id: object, user_id: object
) -> FrameManager:
    """The capability for the frame's owner or a co-manager; PhotoAccessDenied
    for everyone else."""
    if (
        not isinstance(device_id, str)
        or not device_dirs.is_valid_device_id(device_id)
        or not isinstance(user_id, int)
        or isinstance(user_id, bool)
    ):
        raise PhotoAccessDenied()
    if not fleet_db.is_user_active(conn, user_id):
        raise PhotoAccessDenied()
    owner = fleet_db.get_device_owner(conn, device_id)
    if owner is None:
        raise PhotoAccessDenied()
    if owner != user_id and not fleet_db.is_co_manager(conn, device_id, user_id):
        raise PhotoAccessDenied()
    return FrameManager(device_id, user_id, _GRANT)


def _require(manager: object) -> FrameManager:
    if not isinstance(manager, FrameManager) or manager._grant is not _GRANT:
        raise PhotoAccessDenied()
    return manager


def _stage(directory: str, data: bytes) -> str:
    """Write `data` to a fresh 0600 temp file in `directory`; return its path."""
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=photo_paths.TEMP_PREFIX)
    try:
        os.fchmod(fd, photo_paths.FILE_MODE)
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
    except BaseException:
        with contextlib.suppress(OSError):
            os.close(fd)
        with contextlib.suppress(FileNotFoundError):
            os.unlink(tmp)
        raise
    return tmp


def _publish(
    conn: sqlite3.Connection,
    manager: FrameManager,
    root: str,
    stored: normalize.StoredPhoto,
    tmp: str,
    photo_id: str,
    now: int,
) -> str:
    """Inside one write transaction: check quotas, insert the row and move the
    temp file to its final name. Returns the final path. If the transaction
    fails after the move (including at COMMIT), the final file is removed."""
    final = photo_paths.photo_file(root, manager.device_id, photo_id)
    published = False
    try:
        with fleet_db.transaction(conn):
            photo_quota.check(
                conn, manager.device_id, len(stored.jpeg),
                photo_quota.free_disk_bytes(root))
            fleet_db.insert_photo(
                conn, photo_id, manager.device_id, len(stored.jpeg),
                stored.width, stored.height, manager.user_id, now)
            os.replace(tmp, final)
            published = True
    except BaseException:
        if published:
            with contextlib.suppress(FileNotFoundError):
                os.unlink(final)
        raise
    return final


def add(
    manager: FrameManager, conn: sqlite3.Connection, root: str, raw: bytes, now: int
) -> str:
    """Normalise an upload and store it; returns the new photo id.

    `PhotoRejected` (unusable image) and `QuotaExceeded` (a limit) propagate
    with their codes; either way nothing is left in the database or on disk.
    The original bytes are never written anywhere.
    """
    manager = _require(manager)
    with _NORMALIZE_SLOTS:
        stored = normalize.normalize_upload(raw)
    directory = photo_paths.ensure_photo_dir(root, manager.device_id)
    photo_id = photo_paths.new_photo_id()
    tmp = _stage(directory, stored.jpeg)
    try:
        _publish(conn, manager, root, stored, tmp, photo_id, now)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(tmp)
        raise
    return photo_id


def list_photos(manager: FrameManager, conn: sqlite3.Connection) -> list[PhotoMeta]:
    """Metadata of the frame's photos in upload order."""
    manager = _require(manager)
    return [
        PhotoMeta(
            id=str(r["id"]), width=int(r["width"]), height=int(r["height"]),
            size_bytes=int(r["size_bytes"]), created_at=int(r["created_at"]),
            seq=int(r["seq"]))
        for r in fleet_db.list_photo_rows(conn, manager.device_id)
    ]


def _frame_row(
    manager: FrameManager, conn: sqlite3.Connection, photo_id: object
) -> sqlite3.Row:
    if not photo_paths.is_valid_photo_id(photo_id):
        raise PhotoNotFound()
    row = fleet_db.get_photo_row(conn, manager.device_id, str(photo_id))
    if row is None:
        raise PhotoNotFound()
    return row


def _read_regular(path: str) -> bytes:
    """Read a regular file without following a link at the final component."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    except OSError as exc:
        if exc.errno in (errno.ENOENT, errno.ELOOP):
            raise PhotoNotFound() from None
        raise
    with os.fdopen(fd, "rb") as fh:
        if not stat.S_ISREG(os.fstat(fh.fileno()).st_mode):
            raise PhotoNotFound()
        return fh.read()


def read_photo(
    manager: FrameManager, conn: sqlite3.Connection, root: str, photo_id: str
) -> bytes:
    """The stored JPEG of one of this frame's photos; PhotoNotFound for an
    unknown, malformed or other-frame id, or a missing or linked file."""
    manager = _require(manager)
    row = _frame_row(manager, conn, photo_id)
    try:
        path = photo_paths.photo_file(root, manager.device_id, str(row["id"]))
    except ValueError:
        raise PhotoNotFound() from None
    return _read_regular(path)


def delete_photo(
    manager: FrameManager, conn: sqlite3.Connection, root: str, photo_id: str
) -> None:
    """Delete the row in a transaction, then unlink the file after commit.
    A missing file is fine; a symlink in the file's place is left alone."""
    manager = _require(manager)
    if not photo_paths.is_valid_photo_id(photo_id):
        raise PhotoNotFound()
    with fleet_db.transaction(conn):
        if not fleet_db.delete_photo_row(conn, manager.device_id, photo_id):
            raise PhotoNotFound()
    try:
        path = photo_paths.photo_file(root, manager.device_id, photo_id)
    except ValueError:
        return
    with contextlib.suppress(FileNotFoundError):
        os.unlink(path)
